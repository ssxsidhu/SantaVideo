import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT, loadConfig, type LipsyncProviderId } from "./config.js";
import {
  businessPackageMargin,
  businessReferredCustomMargin,
  customVideoCost,
  instantVideoCost,
  libraryCost,
  margin,
  nameClipCost,
  type MarginLine,
} from "./costModel.js";

const usd = (value: number) => `$${value.toFixed(value < 1 ? 3 : 2)}`;
const pct = (value: number) => `${(value * 100).toFixed(0)}%`;
const marginCell = (line: MarginLine) => `${usd(line.marginUsd)} (${pct(line.marginPct)})`;

function table(header: string[], rows: string[][]): string {
  const lines = [`| ${header.join(" | ")} |`, `|${header.map(() => "---").join("|")}|`];
  for (const row of rows) lines.push(`| ${row.join(" | ")} |`);
  return lines.join("\n");
}

function buildReport(): string {
  const inputs = loadConfig();
  const { rates, pricing, assumptions } = inputs;
  const providers = Object.keys(rates.lipsync) as LipsyncProviderId[];
  const label = (p: LipsyncProviderId) => rates.lipsync[p].label;
  const [lowVolume, midVolume, highVolume] = assumptions.amortizationScenarios as [number, number, number];
  const instantPrice = pricing.products.instant.priceUsd;
  const customPrice = pricing.products.custom.priceUsd;

  const sections: string[] = [];
  sections.push(`# Phase 0 cost model (generated)\n\nGenerated by \`npm run bench:costs\` from \`config/*.json\`. Vendor rates retrieved ${rates.retrieved}. **Estimates from published prices — replace with measured numbers after the benchmark run.**`);

  sections.push(
    "## 1. Name library and rare names\n\n" +
      table(
        ["Provider", "Per name clip (1 take)", "Rare-name render", "Library EN", "Library FR", "Library total"],
        providers.map((p) => {
          const en = libraryCost(inputs, p, "en");
          const fr = libraryCost(inputs, p, "fr");
          return [label(p), usd(nameClipCost(inputs, p)), usd(nameClipCost(inputs, p)), usd(en), usd(fr), usd(en + fr)];
        }),
      ) +
      `\n\nAssumes ${assumptions.nameClip.seconds}s greeting clip, ${assumptions.nameClip.takesPerName} takes/name, ` +
      `${assumptions.library.namesPerLanguage.en} EN + ${assumptions.library.namesPerLanguage.fr} FR names.`,
  );

  sections.push(
    `## 2. Instant video (${usd(instantPrice)}) — cost per sale and gross margin\n\n` +
      `Library cost amortized over total instant videos delivered (B2C + business). ${pct(assumptions.instant.rareNameShare)} of orders need a rare-name render.\n\n` +
      table(
        ["Provider", `Cost @ ${lowVolume}`, `Margin @ ${lowVolume}`, `Cost @ ${midVolume}`, `Margin @ ${midVolume}`, `Margin @ ${highVolume}`],
        providers.map((p) => {
          const low = margin(rates, instantPrice, instantVideoCost(inputs, p, lowVolume));
          const mid = margin(rates, instantPrice, instantVideoCost(inputs, p, midVolume));
          const high = margin(rates, instantPrice, instantVideoCost(inputs, p, highVolume));
          return [label(p), usd(low.costUsd), marginCell(low), usd(mid.costUsd), marginCell(mid), marginCell(high)];
        }),
      ) +
      "\n\nCost includes Stripe fee (US card rate).",
  );

  sections.push(
    `## 3. Custom video (${usd(customPrice)}) — cost per sale and gross margin\n\n` +
      `*Full* = lip-sync all ${assumptions.custom.spokenSeconds}s. *Personalized-only* = fixed template sentences pre-rendered once, only ~${assumptions.custom.personalizedSeconds}s of personalized sentences lip-synced per order.\n\n` +
      table(
        ["Provider", "Cost (full)", "Margin (full)", "Cost (personalized-only)", "Margin (personalized-only)", "Business-referred margin (full, after 20% share)"],
        providers.map((p) => {
          const full = margin(rates, customPrice, customVideoCost(inputs, p, "fullLipsync"));
          const partial = margin(rates, customPrice, customVideoCost(inputs, p, "personalizedOnly"));
          const referred = businessReferredCustomMargin(inputs, p, "fullLipsync");
          return [label(p), usd(full.costUsd), marginCell(full), usd(partial.costUsd), marginCell(partial), marginCell(referred)];
        }),
      ),
  );

  const packages = [
    ["Small", pricing.products.businessSmall],
    ["Standard", pricing.products.businessStandard],
    ["Large", pricing.products.businessLarge],
  ] as const;
  sections.push(
    `## 4. Business packages — margin if every slot is used (library amortized @ ${midVolume} videos)\n\n` +
      table(
        ["Provider", ...packages.map(([name, pkg]) => `${name} ${usd(pkg.priceUsd)} / ${pkg.children}`)],
        providers.map((p) => [label(p), ...packages.map(([, pkg]) => marginCell(businessPackageMargin(inputs, p, pkg, midVolume)))]),
      ),
  );

  return sections.join("\n\n") + "\n";
}

try {
  const report = buildReport();
  const outPath = join(REPO_ROOT, "docs", "phase0-cost-model.md");
  writeFileSync(outPath, report);
  console.log(report);
  console.log(`\nWrote ${outPath}`);
} catch (error) {
  console.error("Cost report failed:", error);
  process.exitCode = 1;
}
